/** "Pennsylvania", "pa" or "PA" → "PA"; anything that is not a US state → "". */
export function toStateCode(value: string | null | undefined): string {
  const v = (value ?? "").trim()
  if (!v) return ""
  const upper = v.toUpperCase()
  if (US_STATES[upper]) return upper
  const hit = Object.entries(US_STATES).find(
    ([, name]) => name.toLowerCase() === v.toLowerCase()
  )
  return hit ? hit[0] : ""
}
